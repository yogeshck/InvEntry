/*
    InvEntry Database Migration
    File: 002_Add_Customer_Advance_And_Schemes.sql
    Purpose:
        Customer advances and jewellery savings schemes (RD), kept per customer
        account with an append-only ledger. Replaces the client-side balance in
        LEDGERS_HEADER, which is not reduced when an advance or RD is adjusted
        on an invoice.

        SCHEME_PLAN                    scheme definition: amount or weight based, tenure, refund rules
        SCHEME_BENEFIT_RULE            benefits of a plan (installment waiver, % bonus, making-charge waiver, bonus grams)
        CUSTOMER_ADVANCE_ACCOUNT       one row per customer advance or scheme enrollment; cached balance
        SCHEME_ENROLLMENT              scheme terms of a SCHEME account, snapshotted at enrollment
        SCHEME_INSTALLMENT             monthly installment schedule
        ADVANCE_LEDGER                 append-only money / weight movements of an account
        SCHEME_INSTALLMENT_ALLOCATION  which installments a receipt paid
        ADVANCE_CLOSURE                maturity / pre-closure / refund calculation and approval
        CUSTOMER_ADVANCE_BALANCE_CHECK_VIEW  accounts whose cached balance differs from the ledger

    Conventions:
        Amounts DECIMAL(18,2), weights DECIMAL(18,3) grams, rates DECIMAL(18,2) per gram.
        ADVANCE_LEDGER signs: credit to the customer is positive (OPENING, RECEIPT, BONUS),
        use of the balance is negative (ADJUSTMENT, REFUND, DEDUCTION, FORFEITURE).
        Ledger rows are never updated or deleted; corrections are REVERSAL rows.
        CUSTOMER_ADVANCE_ACCOUNT.BALANCE_* is updated in the same transaction as each
        ledger insert, with a conditional UPDATE (BALANCE_AMOUNT >= @Amount).

    Opening balances from LEDGERS_HEADER are migrated separately by
    003_Migrate_Ledger_Opening_Balances.sql (preview first).

    QUOTED_IDENTIFIER: the filtered unique indexes require QUOTED_IDENTIFIER ON for
    every session that writes to these tables. EF Core / SqlClient and SSMS use ON;
    the ODBC sqlcmd needs -I, and stored procedures touching these tables must be
    created with QUOTED_IDENTIFIER ON.

      sqlcmd -S <server> -d mijms -E -I -b -i 002_Add_Customer_Advance_And_Schemes.sql

    Date: 2026-10-20

    Safe to rerun: Yes (objects are created only when missing; the view uses CREATE OR ALTER)
*/

SET NOCOUNT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
