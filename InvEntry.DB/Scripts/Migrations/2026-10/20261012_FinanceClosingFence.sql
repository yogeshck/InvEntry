/* Phase 4B durable daily-closing fence. Does not modify financial records. */
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.FINANCE_CLOSING_FENCE', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.FINANCE_CLOSING_FENCE
    (
        GKEY bigint IDENTITY(1,1) NOT NULL
            CONSTRAINT PK_FINANCE_CLOSING_FENCE PRIMARY KEY,
        ORG_GKEY int NOT NULL,
        LOCATION_GKEY int NOT NULL,
        BUSINESS_DATE date NOT NULL,
        RESERVATION_ID uniqueidentifier NOT NULL,
        STATUS varchar(20) NOT NULL,
        CREATED_ON_UTC datetime2(7) NOT NULL,
        MODIFIED_ON_UTC datetime2(7) NOT NULL,
        CONSTRAINT CK_FINANCE_CLOSING_FENCE_STATUS CHECK
            (STATUS IN ('RESERVED','UNCERTAIN','CONFIRMED','CANCELLED')),
        CONSTRAINT UX_FINANCE_CLOSING_FENCE_SCOPE_DATE UNIQUE
            (ORG_GKEY, LOCATION_GKEY, BUSINESS_DATE),
        CONSTRAINT UX_FINANCE_CLOSING_FENCE_RESERVATION UNIQUE
            (RESERVATION_ID)
    );
END;

COMMIT TRANSACTION;
