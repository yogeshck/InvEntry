CREATE TABLE [dbo].[SCHEME_INSTALLMENT] (
    GKEY                     INT             IDENTITY (1, 1) NOT NULL,
    SCHEME_ENROLLMENT_GKEY   INT             NOT NULL,
    SEQ_NBR                  INT             NOT NULL,
    DUE_DATE                 DATE            NOT NULL,
    AMOUNT_DUE               DECIMAL (18, 2) NOT NULL,
    AMOUNT_PAID              DECIMAL (18, 2) NOT NULL CONSTRAINT DF_SCHEME_INSTALLMENT_PAID DEFAULT (0),
    WEIGHT_CREDITED          DECIMAL (18, 3) NOT NULL CONSTRAINT DF_SCHEME_INSTALLMENT_WEIGHT DEFAULT (0),
    STATUS                   VARCHAR (10)    NOT NULL CONSTRAINT DF_SCHEME_INSTALLMENT_STATUS DEFAULT ('PENDING'),
    PAID_ON                  DATE            NULL,
    CONSTRAINT PK_SCHEME_INSTALLMENT PRIMARY KEY CLUSTERED (GKEY ASC),
    CONSTRAINT UQ_SCHEME_INSTALLMENT_SEQ UNIQUE (SCHEME_ENROLLMENT_GKEY, SEQ_NBR),
    CONSTRAINT FK_SCHEME_INSTALLMENT_ENROLLMENT FOREIGN KEY (SCHEME_ENROLLMENT_GKEY) REFERENCES [dbo].[SCHEME_ENROLLMENT] (GKEY),
    CONSTRAINT CK_SCHEME_INSTALLMENT_SEQ CHECK (SEQ_NBR BETWEEN 1 AND 12),
    CONSTRAINT CK_SCHEME_INSTALLMENT_AMOUNTS CHECK (AMOUNT_DUE > 0 AND AMOUNT_PAID >= 0 AND WEIGHT_CREDITED >= 0),
    CONSTRAINT CK_SCHEME_INSTALLMENT_STATUS CHECK (STATUS IN ('PENDING', 'PARTIAL', 'PAID', 'OVERDUE', 'WAIVED'))
);

GO

-- Daily overdue marking and payment reminders.
CREATE NONCLUSTERED INDEX IX_SCHEME_INSTALLMENT_DUE
    ON [dbo].[SCHEME_INSTALLMENT] (STATUS, DUE_DATE)
    INCLUDE (SCHEME_ENROLLMENT_GKEY, AMOUNT_DUE, AMOUNT_PAID);
