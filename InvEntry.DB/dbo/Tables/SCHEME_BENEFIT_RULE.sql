CREATE TABLE [dbo].[SCHEME_BENEFIT_RULE] (
    GKEY                   INT             IDENTITY (1, 1) NOT NULL,
    SCHEME_PLAN_GKEY       INT             NOT NULL,
    SEQ_NBR                INT             NOT NULL,
    BENEFIT_TYPE           VARCHAR (25)    NOT NULL,
    -- INSTALLMENT_WAIVER: number of installments; PERCENT_BONUS / MAKING_CHARGE_WAIVER: percent;
    -- BONUS_GRAMS: grams; FLAT_BONUS: rupees.
    BENEFIT_VALUE          DECIMAL (18, 3) NOT NULL,
    APPLIES_ON             VARCHAR (25)    NOT NULL,
    MIN_INSTALLMENTS_PAID  INT             NOT NULL CONSTRAINT DF_SCHEME_BENEFIT_RULE_MIN_PAID DEFAULT (0),
    -- Comma-separated PRODUCT_CATEGORY codes the benefit may be used on; NULL = all.
    ELIGIBLE_CATEGORIES    VARCHAR (500)   NULL,
    IS_ACTIVE              BIT             NOT NULL CONSTRAINT DF_SCHEME_BENEFIT_RULE_ACTIVE DEFAULT (1),
    CONSTRAINT PK_SCHEME_BENEFIT_RULE PRIMARY KEY CLUSTERED (GKEY ASC),
    CONSTRAINT FK_SCHEME_BENEFIT_RULE_PLAN FOREIGN KEY (SCHEME_PLAN_GKEY) REFERENCES [dbo].[SCHEME_PLAN] (GKEY),
    CONSTRAINT UQ_SCHEME_BENEFIT_RULE_SEQ UNIQUE (SCHEME_PLAN_GKEY, SEQ_NBR),
    CONSTRAINT CK_SCHEME_BENEFIT_RULE_TYPE CHECK (BENEFIT_TYPE IN
        ('INSTALLMENT_WAIVER', 'PERCENT_BONUS', 'MAKING_CHARGE_WAIVER', 'BONUS_GRAMS', 'FLAT_BONUS')),
    CONSTRAINT CK_SCHEME_BENEFIT_RULE_VALUE CHECK (BENEFIT_VALUE > 0
        AND (BENEFIT_TYPE NOT IN ('PERCENT_BONUS', 'MAKING_CHARGE_WAIVER') OR BENEFIT_VALUE <= 100)),
    CONSTRAINT CK_SCHEME_BENEFIT_RULE_APPLIES_ON CHECK (APPLIES_ON IN ('MATURITY', 'PRECLOSURE')),
    CONSTRAINT CK_SCHEME_BENEFIT_RULE_MIN_PAID CHECK (MIN_INSTALLMENTS_PAID >= 0)
);
