CREATE TABLE [dbo].[SCHEME_ENROLLMENT] (
    GKEY                     INT             IDENTITY (1, 1) NOT NULL,
    ADVANCE_ACCOUNT_GKEY     INT             NOT NULL,
    SCHEME_PLAN_GKEY         INT             NOT NULL,
    -- JSON copy of SCHEME_PLAN and its SCHEME_BENEFIT_RULE rows at enrollment.
    -- Later plan changes never affect an existing enrollment.
    TERMS_SNAPSHOT           NVARCHAR (MAX)  NOT NULL,
    INSTALLMENT_AMOUNT       DECIMAL (18, 2) NOT NULL,
    START_DATE               DATE            NOT NULL,
    MATURITY_DATE            DATE            NOT NULL,
    INSTALLMENTS_PAID        INT             NOT NULL CONSTRAINT DF_SCHEME_ENROLLMENT_PAID DEFAULT (0),
    MISSED_COUNT             INT             NOT NULL CONSTRAINT DF_SCHEME_ENROLLMENT_MISSED DEFAULT (0),
    BONUS_FORFEITED          BIT             NOT NULL CONSTRAINT DF_SCHEME_ENROLLMENT_FORFEITED DEFAULT (0),
    NOMINEE_NAME             VARCHAR (100)   NULL,
    NOMINEE_RELATION         VARCHAR (30)    NULL,
    NOMINEE_MOBILE           VARCHAR (15)    NULL,
    -- Generated once by the client per enrollment; a retry returns the original.
    CLIENT_REQUEST_ID        UNIQUEIDENTIFIER NULL,
    CREATED_BY               VARCHAR (50)    NOT NULL,
    CREATED_ON               DATETIME2 (7)   NOT NULL CONSTRAINT DF_SCHEME_ENROLLMENT_CREATED_ON DEFAULT (SYSDATETIME()),
    MODIFIED_BY              VARCHAR (50)    NULL,
    MODIFIED_ON              DATETIME2 (7)   NULL,
    CONSTRAINT PK_SCHEME_ENROLLMENT PRIMARY KEY CLUSTERED (GKEY ASC),
    CONSTRAINT UQ_SCHEME_ENROLLMENT_ACCOUNT UNIQUE (ADVANCE_ACCOUNT_GKEY),
    CONSTRAINT FK_SCHEME_ENROLLMENT_ACCOUNT FOREIGN KEY (ADVANCE_ACCOUNT_GKEY) REFERENCES [dbo].[CUSTOMER_ADVANCE_ACCOUNT] (GKEY),
    CONSTRAINT FK_SCHEME_ENROLLMENT_PLAN FOREIGN KEY (SCHEME_PLAN_GKEY) REFERENCES [dbo].[SCHEME_PLAN] (GKEY),
    CONSTRAINT [CK_SCHEME_ENROLLMENT_TERMS_JSON] CHECK (isjson([TERMS_SNAPSHOT])=(1)),
    CONSTRAINT [CK_SCHEME_ENROLLMENT_AMOUNT] CHECK ([INSTALLMENT_AMOUNT]>(0)),
    CONSTRAINT [CK_SCHEME_ENROLLMENT_DATES] CHECK ([MATURITY_DATE]>[START_DATE]),
    CONSTRAINT [CK_SCHEME_ENROLLMENT_COUNTS] CHECK ([INSTALLMENTS_PAID]>=(0) AND [MISSED_COUNT]>=(0))
);
GO
