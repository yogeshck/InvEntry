CREATE TABLE [dbo].[CUSTOMER_ADVANCE_ACCOUNT] (
    GKEY                        INT             IDENTITY (1, 1) NOT NULL,
    TENANT_GKEY                 INT             NULL,
    LOCATION_GKEY               INT             NULL,
    ACCOUNT_NBR                 VARCHAR (50)    NOT NULL,
    ACCOUNT_TYPE                VARCHAR (15)    NOT NULL,
    CUST_GKEY                   INT             NOT NULL,
    MTBL_LEDGERS_GKEY           INT             NOT NULL,
    CUSTOMER_ORDER_GKEY         INT             NULL,
    STATUS                      VARCHAR (20)    NOT NULL CONSTRAINT DF_CUSTOMER_ADVANCE_ACCOUNT_STATUS DEFAULT ('ACTIVE'),
    OPENED_ON                   DATE            NOT NULL,
    CLOSED_ON                   DATE            NULL,
    -- Weight schemes and rate bookings.
    METAL                       NVARCHAR (20)   NULL,
    PURITY                      NVARCHAR (20)   NULL,
    BOOKED_RATE                 DECIMAL (18, 2) NULL,
    VALID_UNTIL                 DATE            NULL,
    -- Cached totals, kept equal to the sum of ADVANCE_LEDGER rows.
    BALANCE_AMOUNT              DECIMAL (18, 2) NOT NULL CONSTRAINT DF_CUSTOMER_ADVANCE_ACCOUNT_BAL_AMT DEFAULT (0),
    BALANCE_WEIGHT              DECIMAL (18, 3) NOT NULL CONSTRAINT DF_CUSTOMER_ADVANCE_ACCOUNT_BAL_WT DEFAULT (0),
    TOTAL_RECEIVED_AMOUNT       DECIMAL (18, 2) NOT NULL CONSTRAINT DF_CUSTOMER_ADVANCE_ACCOUNT_RCV_AMT DEFAULT (0),
    TOTAL_RECEIVED_WEIGHT       DECIMAL (18, 3) NOT NULL CONSTRAINT DF_CUSTOMER_ADVANCE_ACCOUNT_RCV_WT DEFAULT (0),
    IS_OPENING_BALANCE          BIT             NOT NULL CONSTRAINT DF_CUSTOMER_ADVANCE_ACCOUNT_OPENING DEFAULT (0),
    REMARKS                     VARCHAR (250)   NULL,
    CREATED_BY                  VARCHAR (50)    NOT NULL,
    CREATED_ON                  DATETIME2 (7)   NOT NULL CONSTRAINT DF_CUSTOMER_ADVANCE_ACCOUNT_CREATED_ON DEFAULT (SYSDATETIME()),
    MODIFIED_BY                 VARCHAR (50)    NULL,
    MODIFIED_ON                 DATETIME2 (7)   NULL,
    ROW_VERSION                 ROWVERSION      NOT NULL,
    CONSTRAINT PK_CUSTOMER_ADVANCE_ACCOUNT PRIMARY KEY CLUSTERED (GKEY ASC),
    CONSTRAINT UQ_CUSTOMER_ADVANCE_ACCOUNT_NBR UNIQUE (TENANT_GKEY, ACCOUNT_NBR),
    CONSTRAINT FK_CUSTOMER_ADVANCE_ACCOUNT_CUSTOMER FOREIGN KEY (CUST_GKEY) REFERENCES [dbo].[ORG_CUSTOMER] (GKEY),
    CONSTRAINT FK_CUSTOMER_ADVANCE_ACCOUNT_LEDGER FOREIGN KEY (MTBL_LEDGERS_GKEY) REFERENCES [dbo].[MTBL_LEDGERS] (GKEY),
    CONSTRAINT FK_CUSTOMER_ADVANCE_ACCOUNT_ORDER FOREIGN KEY (CUSTOMER_ORDER_GKEY) REFERENCES [dbo].[CUSTOMER_ORDER] (GKEY),
    CONSTRAINT CK_CUSTOMER_ADVANCE_ACCOUNT_TYPE CHECK (ACCOUNT_TYPE IN ('SCHEME', 'ORDER', 'OPEN', 'RATE_BOOKING')),
    CONSTRAINT CK_CUSTOMER_ADVANCE_ACCOUNT_STATUS CHECK (STATUS IN
        ('ACTIVE', 'MATURED', 'LAPSED', 'CLOSURE_PENDING', 'CLOSED')),
    CONSTRAINT CK_CUSTOMER_ADVANCE_ACCOUNT_ORDER CHECK (ACCOUNT_TYPE <> 'ORDER' OR CUSTOMER_ORDER_GKEY IS NOT NULL),
    CONSTRAINT CK_CUSTOMER_ADVANCE_ACCOUNT_RATE_BOOKING CHECK (ACCOUNT_TYPE <> 'RATE_BOOKING'
        OR (METAL IS NOT NULL AND PURITY IS NOT NULL AND BOOKED_RATE > 0 AND VALID_UNTIL IS NOT NULL)),
    CONSTRAINT CK_CUSTOMER_ADVANCE_ACCOUNT_BALANCE CHECK (BALANCE_AMOUNT >= 0 AND BALANCE_WEIGHT >= 0
        AND TOTAL_RECEIVED_AMOUNT >= 0 AND TOTAL_RECEIVED_WEIGHT >= 0),
    CONSTRAINT CK_CUSTOMER_ADVANCE_ACCOUNT_CLOSED CHECK ((STATUS = 'CLOSED' AND CLOSED_ON IS NOT NULL)
        OR (STATUS <> 'CLOSED' AND CLOSED_ON IS NULL))
);

GO

CREATE NONCLUSTERED INDEX IX_CUSTOMER_ADVANCE_ACCOUNT_CUSTOMER
    ON [dbo].[CUSTOMER_ADVANCE_ACCOUNT] (CUST_GKEY, STATUS)
    INCLUDE (ACCOUNT_NBR, ACCOUNT_TYPE, BALANCE_AMOUNT, BALANCE_WEIGHT);

GO

CREATE NONCLUSTERED INDEX IX_CUSTOMER_ADVANCE_ACCOUNT_ORDER
    ON [dbo].[CUSTOMER_ADVANCE_ACCOUNT] (CUSTOMER_ORDER_GKEY)
    WHERE CUSTOMER_ORDER_GKEY IS NOT NULL;

GO

-- explicit account are credited to it.
CREATE UNIQUE NONCLUSTERED INDEX UX_CUSTOMER_ADVANCE_ACCOUNT_OPEN
    ON [dbo].[CUSTOMER_ADVANCE_ACCOUNT] (CUST_GKEY)
    WHERE ACCOUNT_TYPE = 'OPEN' AND STATUS = 'ACTIVE';
