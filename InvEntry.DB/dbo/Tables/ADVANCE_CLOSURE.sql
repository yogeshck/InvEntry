CREATE TABLE [dbo].[ADVANCE_CLOSURE] (
    GKEY                     INT             IDENTITY (1, 1) NOT NULL,
    ADVANCE_ACCOUNT_GKEY     INT             NOT NULL,
    CLOSURE_TYPE             VARCHAR (25)    NOT NULL,
    STATUS                   VARCHAR (10)    NOT NULL CONSTRAINT DF_ADVANCE_CLOSURE_STATUS DEFAULT ('REQUESTED'),
    CLOSURE_DATE             DATE            NOT NULL,
    TOTAL_PAID_AMOUNT        DECIMAL (18, 2) NOT NULL,
    TOTAL_PAID_WEIGHT        DECIMAL (18, 3) NOT NULL CONSTRAINT DF_ADVANCE_CLOSURE_PAID_WT DEFAULT (0),
    METAL_RATE               DECIMAL (18, 2) NULL,
    DAILY_RATE_GKEY          INT             NULL,
    METAL_VALUE              DECIMAL (18, 2) NULL,
    BONUS_AMOUNT             DECIMAL (18, 2) NOT NULL CONSTRAINT DF_ADVANCE_CLOSURE_BONUS_AMT DEFAULT (0),
    BONUS_WEIGHT             DECIMAL (18, 3) NOT NULL CONSTRAINT DF_ADVANCE_CLOSURE_BONUS_WT DEFAULT (0),
    MAKING_WAIVER_PCT        DECIMAL (5, 2)  NOT NULL CONSTRAINT DF_ADVANCE_CLOSURE_MAKING DEFAULT (0),
    DEDUCTION_AMOUNT         DECIMAL (18, 2) NOT NULL CONSTRAINT DF_ADVANCE_CLOSURE_DEDUCTION DEFAULT (0),
    NET_AMOUNT               DECIMAL (18, 2) NOT NULL,
    NET_WEIGHT               DECIMAL (18, 3) NOT NULL CONSTRAINT DF_ADVANCE_CLOSURE_NET_WT DEFAULT (0),
    REFUND_MODE              VARCHAR (50)    NULL,
    REFUND_VOUCHER_GKEY      INT             NULL,
    -- JSON line-by-line calculation, kept for customer disputes.
    CALC_BREAKDOWN           NVARCHAR (MAX)  NULL,
    REQUESTED_BY             VARCHAR (50)    NOT NULL,
    REQUESTED_ON             DATETIME2 (7)   NOT NULL CONSTRAINT DF_ADVANCE_CLOSURE_REQUESTED_ON DEFAULT (SYSDATETIME()),
    APPROVED_BY              VARCHAR (50)    NULL,
    APPROVED_ON              DATETIME2 (7)   NULL,
    COMPLETED_ON             DATETIME2 (7)   NULL,
    CANCEL_REASON            VARCHAR (250)   NULL,
    CONSTRAINT PK_ADVANCE_CLOSURE PRIMARY KEY CLUSTERED (GKEY ASC),
    CONSTRAINT FK_ADVANCE_CLOSURE_ACCOUNT FOREIGN KEY (ADVANCE_ACCOUNT_GKEY) REFERENCES [dbo].[CUSTOMER_ADVANCE_ACCOUNT] (GKEY),
    CONSTRAINT FK_ADVANCE_CLOSURE_DAILY_RATE FOREIGN KEY (DAILY_RATE_GKEY) REFERENCES [dbo].[DAILY_RATE] (GKEY),
    CONSTRAINT FK_ADVANCE_CLOSURE_VOUCHER FOREIGN KEY (REFUND_VOUCHER_GKEY) REFERENCES [dbo].[VOUCHER] (gkey),
    CONSTRAINT CK_ADVANCE_CLOSURE_TYPE CHECK (CLOSURE_TYPE IN
        ('MATURITY_REDEMPTION', 'PRECLOSURE_REDEMPTION', 'PRECLOSURE_REFUND', 'ADVANCE_REFUND')),
    CONSTRAINT CK_ADVANCE_CLOSURE_STATUS CHECK (STATUS IN ('REQUESTED', 'APPROVED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT CK_ADVANCE_CLOSURE_AMOUNTS CHECK (TOTAL_PAID_AMOUNT >= 0 AND TOTAL_PAID_WEIGHT >= 0
        AND BONUS_AMOUNT >= 0 AND BONUS_WEIGHT >= 0 AND DEDUCTION_AMOUNT >= 0 AND NET_AMOUNT >= 0 AND NET_WEIGHT >= 0
        AND (METAL_VALUE IS NULL OR METAL_VALUE >= 0)),
    CONSTRAINT CK_ADVANCE_CLOSURE_MAKING CHECK (MAKING_WAIVER_PCT BETWEEN 0 AND 100),
    CONSTRAINT CK_ADVANCE_CLOSURE_CALC_JSON CHECK (CALC_BREAKDOWN IS NULL OR ISJSON(CALC_BREAKDOWN) = 1),
    CONSTRAINT CK_ADVANCE_CLOSURE_APPROVAL CHECK (STATUS NOT IN ('APPROVED', 'COMPLETED')
        OR (APPROVED_BY IS NOT NULL AND APPROVED_ON IS NOT NULL)),
    CONSTRAINT CK_ADVANCE_CLOSURE_CANCEL CHECK (STATUS <> 'CANCELLED' OR CANCEL_REASON IS NOT NULL)
);

GO

-- At most one closure in progress or completed per account.
CREATE UNIQUE NONCLUSTERED INDEX UX_ADVANCE_CLOSURE_OPEN
    ON [dbo].[ADVANCE_CLOSURE] (ADVANCE_ACCOUNT_GKEY)
    WHERE STATUS <> 'CANCELLED';
