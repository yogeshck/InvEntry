CREATE TABLE [dbo].[ADVANCE_LEDGER] (
    GKEY                     BIGINT          IDENTITY (1, 1) NOT NULL,
    ADVANCE_ACCOUNT_GKEY     INT             NOT NULL,
    ENTRY_TYPE               VARCHAR (15)    NOT NULL,
    ENTRY_DATE               DATE            NOT NULL,
    AMOUNT                   DECIMAL (18, 2) NOT NULL,
    WEIGHT                   DECIMAL (18, 3) NOT NULL CONSTRAINT DF_ADVANCE_LEDGER_WEIGHT DEFAULT (0),
    METAL_RATE               DECIMAL (18, 2) NULL,
    DAILY_RATE_GKEY          INT             NULL,
    VOUCHER_GKEY             INT             NULL,
    INVOICE_GKEY             INT             NULL,
    INVOICE_NBR              VARCHAR (50)    NULL,
    ADVANCE_CLOSURE_GKEY     INT             NULL,
    REVERSES_LEDGER_GKEY     BIGINT          NULL,
    -- Idempotency key of the business event, e.g. INVOICE-15023-ADJ-7 or OPENING-15100-1000.
    SOURCE_REF               VARCHAR (100)   NOT NULL,
    NARRATION                VARCHAR (250)   NULL,
    CREATED_BY               VARCHAR (50)    NOT NULL,
    CREATED_ON               DATETIME2 (7)   NOT NULL CONSTRAINT DF_ADVANCE_LEDGER_CREATED_ON DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_ADVANCE_LEDGER PRIMARY KEY CLUSTERED (GKEY ASC),
    CONSTRAINT UQ_ADVANCE_LEDGER_SOURCE_REF UNIQUE (SOURCE_REF),
    CONSTRAINT FK_ADVANCE_LEDGER_ACCOUNT FOREIGN KEY (ADVANCE_ACCOUNT_GKEY) REFERENCES [dbo].[CUSTOMER_ADVANCE_ACCOUNT] (GKEY),
    CONSTRAINT FK_ADVANCE_LEDGER_DAILY_RATE FOREIGN KEY (DAILY_RATE_GKEY) REFERENCES [dbo].[DAILY_RATE] (GKEY),
    CONSTRAINT FK_ADVANCE_LEDGER_VOUCHER FOREIGN KEY (VOUCHER_GKEY) REFERENCES [dbo].[VOUCHER] (gkey),
    CONSTRAINT FK_ADVANCE_LEDGER_INVOICE FOREIGN KEY (INVOICE_GKEY) REFERENCES [dbo].[INVOICE_HEADER] (GKEY),
    CONSTRAINT FK_ADVANCE_LEDGER_CLOSURE FOREIGN KEY (ADVANCE_CLOSURE_GKEY) REFERENCES [dbo].[ADVANCE_CLOSURE] (GKEY),
    CONSTRAINT FK_ADVANCE_LEDGER_REVERSES FOREIGN KEY (REVERSES_LEDGER_GKEY) REFERENCES [dbo].[ADVANCE_LEDGER] (GKEY),
    CONSTRAINT [CK_ADVANCE_LEDGER_TYPE] CHECK ([ENTRY_TYPE]='REVERSAL' OR [ENTRY_TYPE]='FORFEITURE' OR [ENTRY_TYPE]='DEDUCTION' OR [ENTRY_TYPE]='REFUND' OR [ENTRY_TYPE]='ADJUSTMENT' OR [ENTRY_TYPE]='BONUS' OR [ENTRY_TYPE]='RECEIPT' OR [ENTRY_TYPE]='OPENING'),
    CONSTRAINT [CK_ADVANCE_LEDGER_NONZERO] CHECK ([AMOUNT]<>(0) OR [WEIGHT]<>(0)),
    CONSTRAINT [CK_ADVANCE_LEDGER_SIGN] CHECK (([ENTRY_TYPE]='BONUS' OR [ENTRY_TYPE]='RECEIPT' OR [ENTRY_TYPE]='OPENING') AND [AMOUNT]>=(0) AND [WEIGHT]>=(0) OR ([ENTRY_TYPE]='FORFEITURE' OR [ENTRY_TYPE]='DEDUCTION' OR [ENTRY_TYPE]='REFUND' OR [ENTRY_TYPE]='ADJUSTMENT') AND [AMOUNT]<=(0) AND [WEIGHT]<=(0) OR [ENTRY_TYPE]='REVERSAL'),
    CONSTRAINT [CK_ADVANCE_LEDGER_REVERSAL] CHECK ([ENTRY_TYPE]='REVERSAL' AND [REVERSES_LEDGER_GKEY] IS NOT NULL OR [ENTRY_TYPE]<>'REVERSAL' AND [REVERSES_LEDGER_GKEY] IS NULL),
    CONSTRAINT [CK_ADVANCE_LEDGER_ADJUSTMENT_INVOICE] CHECK ([ENTRY_TYPE]<>'ADJUSTMENT' OR [INVOICE_GKEY] IS NOT NULL)
);
GO
