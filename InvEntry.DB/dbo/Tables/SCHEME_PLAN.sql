CREATE TABLE [dbo].[SCHEME_PLAN] (
    GKEY                     INT             IDENTITY (1, 1) NOT NULL,
    TENANT_GKEY              INT             NULL,
    PLAN_CODE                VARCHAR (30)    NOT NULL,
    PLAN_NAME                VARCHAR (100)   NOT NULL,
    SCHEME_TYPE              VARCHAR (10)    NOT NULL,
    METAL                    NVARCHAR (20)   NULL,
    PURITY                   NVARCHAR (20)   NULL,
    TENURE_MONTHS            INT             NOT NULL,
    AMOUNT_FIXED             BIT             NOT NULL CONSTRAINT DF_SCHEME_PLAN_AMOUNT_FIXED DEFAULT (1),
    MIN_INSTALLMENT_AMOUNT   DECIMAL (18, 2) NOT NULL,
    MAX_INSTALLMENT_AMOUNT   DECIMAL (18, 2) NULL,
    GRACE_DAYS               INT             NOT NULL CONSTRAINT DF_SCHEME_PLAN_GRACE_DAYS DEFAULT (0),
    MAX_MISSED_FOR_BONUS     INT             NOT NULL CONSTRAINT DF_SCHEME_PLAN_MAX_MISSED_BONUS DEFAULT (0),
    MAX_MISSED_BEFORE_LAPSE  INT             NULL,
    MIN_MONTHS_FOR_REFUND    INT             NOT NULL CONSTRAINT DF_SCHEME_PLAN_MIN_MONTHS_REFUND DEFAULT (0),
    REFUND_DEDUCTION_PCT     DECIMAL (5, 2)  NOT NULL CONSTRAINT DF_SCHEME_PLAN_REFUND_DEDUCTION DEFAULT (0),
    REFUND_BASIS             VARCHAR (20)    NOT NULL CONSTRAINT DF_SCHEME_PLAN_REFUND_BASIS DEFAULT ('AMOUNT_PAID'),
    PRECLOSURE_BONUS         VARCHAR (10)    NOT NULL CONSTRAINT DF_SCHEME_PLAN_PRECLOSURE_BONUS DEFAULT ('NONE'),
    VALID_FROM               DATE            NOT NULL,
    VALID_TO                 DATE            NULL,
    STATUS                   VARCHAR (10)    NOT NULL CONSTRAINT DF_SCHEME_PLAN_STATUS DEFAULT ('ACTIVE'),
    TERMS_TEXT               NVARCHAR (MAX)  NULL,
    CREATED_BY               VARCHAR (50)    NOT NULL,
    CREATED_ON               DATETIME2 (7)   NOT NULL CONSTRAINT DF_SCHEME_PLAN_CREATED_ON DEFAULT (SYSDATETIME()),
    MODIFIED_BY              VARCHAR (50)    NULL,
    MODIFIED_ON              DATETIME2 (7)   NULL,
    CONSTRAINT PK_SCHEME_PLAN PRIMARY KEY CLUSTERED (GKEY ASC),
    CONSTRAINT UQ_SCHEME_PLAN_CODE UNIQUE (TENANT_GKEY, PLAN_CODE),
    CONSTRAINT [CK_SCHEME_PLAN_TYPE] CHECK ([SCHEME_TYPE]='WEIGHT' OR [SCHEME_TYPE]='AMOUNT'),
    CONSTRAINT [CK_SCHEME_PLAN_WEIGHT_METAL] CHECK ([SCHEME_TYPE]='AMOUNT' OR [METAL] IS NOT NULL AND [PURITY] IS NOT NULL),
    -- Advances for goods must be adjusted within 365 days (Companies Act deposit rules).
    CONSTRAINT [CK_SCHEME_PLAN_TENURE] CHECK ([TENURE_MONTHS]>=(1) AND [TENURE_MONTHS]<=(12)),
    CONSTRAINT [CK_SCHEME_PLAN_AMOUNTS] CHECK ([MIN_INSTALLMENT_AMOUNT]>(0) AND ([MAX_INSTALLMENT_AMOUNT] IS NULL OR [MAX_INSTALLMENT_AMOUNT]>=[MIN_INSTALLMENT_AMOUNT])),
    CONSTRAINT [CK_SCHEME_PLAN_COUNTS] CHECK ([GRACE_DAYS]>=(0) AND [MAX_MISSED_FOR_BONUS]>=(0) AND ([MAX_MISSED_BEFORE_LAPSE] IS NULL OR [MAX_MISSED_BEFORE_LAPSE]>=(0)) AND [MIN_MONTHS_FOR_REFUND]>=(0)),
    CONSTRAINT [CK_SCHEME_PLAN_REFUND_DEDUCTION] CHECK ([REFUND_DEDUCTION_PCT]>=(0) AND [REFUND_DEDUCTION_PCT]<=(100)),
    CONSTRAINT [CK_SCHEME_PLAN_REFUND_BASIS] CHECK ([REFUND_BASIS]='LOWER_OF' OR [REFUND_BASIS]='GOLD_VALUE' OR [REFUND_BASIS]='AMOUNT_PAID'),
    CONSTRAINT [CK_SCHEME_PLAN_PRECLOSURE_BONUS] CHECK ([PRECLOSURE_BONUS]='PRORATED' OR [PRECLOSURE_BONUS]='NONE'),
    CONSTRAINT [CK_SCHEME_PLAN_DATES] CHECK ([VALID_TO] IS NULL OR [VALID_TO]>=[VALID_FROM]),
    CONSTRAINT [CK_SCHEME_PLAN_STATUS] CHECK ([STATUS]='RETIRED' OR [STATUS]='ACTIVE' OR [STATUS]='DRAFT')
);
GO
